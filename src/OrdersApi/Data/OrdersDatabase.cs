namespace OrdersApi.Data;

internal static class OrdersDatabase
{
    public const string DirectDataSourceName = "direct";

    // No unique constraint on message_id: duplicates are what we want to see.
    private const string CreateSql = """
                                     CREATE EXTENSION IF NOT EXISTS pg_stat_statements;
                                     CREATE TABLE IF NOT EXISTS orders (
                                         id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         message_id text NOT NULL,
                                         delivery_attempt_header integer,
                                         created_at timestamptz NOT NULL
                                     );
                                     """;

    public static async Task EnsureCreatedAsync(NpgsqlDataSource direct, CancellationToken cancellationToken)
    {
        await using var command = direct.CreateCommand(CreateSql);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }

    // Opens one connection through the DbContext (so through toxiproxy) and logs where it went.
    public static async Task LogConnectionTargetAsync(
        IServiceProvider services,
        ILogger logger,
        CancellationToken cancellationToken)
    {
        await using var scope      = services.CreateAsyncScope();
        var             db         = scope.ServiceProvider.GetRequiredService<OrdersDbContext>();
        var             connection = (NpgsqlConnection)db.Database.GetDbConnection();

        await db.Database.OpenConnectionAsync(cancellationToken);
        try
        {
            logger.LogInformation(
                "OrdersDatabase connected to {Host}:{Port} (database {Database})",
                connection.Host,
                connection.Port,
                connection.Database);
        }
        finally
        {
            await db.Database.CloseConnectionAsync();
        }
    }

    public static object Describe(IServiceProvider services)
    {
        using var scope    = services.CreateScope();
        var       db       = scope.ServiceProvider.GetRequiredService<OrdersDbContext>();
        var       builder  = new NpgsqlConnectionStringBuilder(db.Database.GetConnectionString());
        var       strategy = db.Database.CreateExecutionStrategy();

        return new
        {
            host                  = builder.Host,
            port                  = builder.Port,
            timeoutSeconds        = builder.Timeout,
            commandTimeoutSeconds = db.Database.GetCommandTimeout() ?? builder.CommandTimeout,
            maxPoolSize           = builder.MaxPoolSize,
            executionStrategy     = strategy.GetType().FullName,
            retriesOnFailure      = strategy.RetriesOnFailure,
        };
    }
}